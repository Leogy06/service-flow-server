import assert from "node:assert/strict";
import { createServer } from "node:http";
import process from "node:process";
import { withBrowser, until, delay } from "../../../frontend/tests/browser-harness.mjs";

export async function runWorkflowBrowser({ app, slug, requestId, staffId, prisma, organizationId, dropNextPayment }) {
  await withBrowser(createServer(app), `/${slug}/service-requests?requestId=${requestId}`, async ({ call, origin, evaluate, ready, click, clickText, fill }) => {
    const text = (value) => until(() => evaluate(`document.body.textContent.includes(${JSON.stringify(value)})`), "Missing text: " + value);
    const closeDialog = () => until(() => evaluate("!document.querySelector('[data-slot=dialog-content]')"), "Dialog did not close");
    const navigate = async (path) => { await call("Page.navigate", { url: origin + path }); };
    await ready("[data-slot=sheet-content] dl");
    await clickText("[data-slot=sheet-content] button", "Create job");
    await ready("#job-staff");
    await clickText("[data-slot=dialog-content] button", "Save job");
    await text("Select a staff member");
    const staff = await prisma.user.findUniqueOrThrow({ where: { id: staffId }, select: { firstName: true, lastName: true } });
    await click('document.querySelector("#job-staff")');
    await ready('input[aria-label="Search staff by name"]');
    await fill('input[aria-label="Search staff by name"]', staff.firstName);
    await clickText("#job-staff-options [role=option]", `${staff.firstName} ${staff.lastName}`);
    await fill("#job-description", "Browser completed work");
    await fill("#job-location", "Manila");
    await clickText("[data-slot=dialog-content] button", "Save job");
    await closeDialog();
    await text("Manage job");
    const job = await prisma.job.findFirst({ where: { organizationId, serviceRequestId: requestId } });
    assert.ok(job); assert.equal(job.assignedStaffId, staffId);
    await navigate(`/${slug}/jobs?jobId=${job.id}`);
    await ready("[data-slot=sheet-content] dl");
    await clickText("[data-slot=sheet-content] button", "Start job");
    await until(() => evaluate("[...document.querySelectorAll('[data-slot=sheet-content] dd')].some(el=>el.textContent==='In progress')"), "Job did not start");
    assert.equal((await prisma.serviceRequest.findUnique({ where: { id: requestId } })).status, "IN_PROGRESS");
    await fill("#job-status-note", "All work done");
    await clickText("[data-slot=sheet-content] button", "Complete job");
    await until(() => evaluate("[...document.querySelectorAll('[data-slot=sheet-content] dd')].some(el=>el.textContent==='Completed')"), "Job did not complete");
    await text("Complete the parent request before creating");
    assert.equal((await prisma.serviceRequest.findUnique({ where: { id: requestId } })).status, "IN_PROGRESS");
    await navigate(`/${slug}/service-requests?requestId=${requestId}`);
    await ready("[data-slot=sheet-content] dl");
    await clickText("[data-slot=sheet-content] button", "Complete request");
    await until(() => evaluate("[...document.querySelectorAll('[data-slot=sheet-content] dd')].some(el=>el.textContent==='Completed')"), "Request did not complete");
    await navigate(`/${slug}/jobs?jobId=${job.id}`);
    await ready("[data-slot=sheet-content] dl");
    await clickText("[data-slot=sheet-content] button", "Create invoice");
    await ready("#invoice-price-0");
    assert.equal(await evaluate("document.querySelector('#invoice-price-0').value"), "100.25");
    await clickText("[data-slot=dialog-content] button", "Save invoice");
    await closeDialog();
    await text("Invoice items");
    // Prior steps navigate full documents. Monitor payment errors in this final document.
    await evaluate("window.workflowRejections=[]; window.addEventListener('unhandledrejection',e=>window.workflowRejections.push(String(e.reason)))");
    const invoice = await prisma.invoice.findFirst({ where: { jobId: job.id, organizationId } });
    assert.ok(invoice); assert.equal(invoice.total.toFixed(2), "100.25");

    await clickText("[data-slot=sheet-content] button", "Record payment");
    await ready("#payment-amount");
    await fill("#payment-amount", "1000");
    await clickText("[data-slot=dialog-content] button", "Record payment");
    await text("Payment exceeds the outstanding balance");
    await until(() => evaluate("!document.querySelector('#payment-amount').closest('fieldset').disabled"), "Rejected payment fields did not unlock");
    await fill("#payment-amount", "40");
    await clickText("[data-slot=dialog-content] button", "Retry payment");
    await closeDialog();
    await text("Partially paid");
    assert.equal((await prisma.invoice.findUnique({ where: { id: invoice.id } })).amountPaid.toFixed(2), "40.00");

    await clickText("[data-slot=sheet-content] button", "Record payment"); await ready("#payment-amount");
    await fill("#payment-amount", "20");
    dropNextPayment();
    await clickText("[data-slot=dialog-content] button", "Record payment");
    await text("Payment details are kept for a safe retry.");
    assert.equal((await prisma.invoice.findUnique({ where: { id: invoice.id } })).amountPaid.toFixed(2), "60.00");
    await clickText("[data-slot=dialog-content] button", "Close"); await closeDialog();
    await clickText("[data-slot=sheet-content] button", "Record payment"); await ready("#payment-amount");
    assert.equal(await evaluate("document.querySelector('#payment-amount').value"), "20");
    await clickText("[data-slot=dialog-content] button", "Confirm pending payment"); await closeDialog();
    assert.equal(await prisma.payment.count({ where: { invoiceId: invoice.id } }), 2);
    assert.equal((await prisma.invoice.findUnique({ where: { id: invoice.id } })).amountPaid.toFixed(2), "60.00");
    await clickText("[data-slot=sheet-content] button", "Record payment"); await ready("#payment-amount");
    assert.equal(await evaluate("document.querySelector('#payment-amount').value"), "40.25");
    await clickText("[data-slot=dialog-content] button", "Record payment"); await closeDialog();
    await until(() => evaluate("document.querySelector('[data-slot=sheet-content]').textContent.includes('Paid') && ![...document.querySelectorAll('[data-slot=sheet-content] button')].some(el=>el.textContent==='Record payment')"), "Paid invoice did not refresh");
    const paid = await prisma.invoice.findUnique({ where: { id: invoice.id } });
    assert.equal(paid.status, "PAID"); assert.equal(paid.amountPaid.toFixed(2), "100.25");
    assert.equal(await prisma.payment.count({ where: { invoiceId: invoice.id } }), 3);
    assert.equal(await prisma.auditLog.count({ where: { entityId: invoice.id, action: "payment.invoice.success", organizationId } }), 3);
    assert.deepEqual(await evaluate("window.workflowRejections"), []);
    await call("Emulation.setDeviceMetricsOverride", { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
    await delay(200);
    assert.equal(await evaluate("document.querySelector('[data-slot=sheet-content]').getBoundingClientRect().width <= window.innerWidth"), true);
    await call("Emulation.clearDeviceMetricsOverride");
    process.stdout.write("Browser request -> assignment -> completion -> invoice -> partial/full payments and lost-response recovery passed.\n");
  });
}
